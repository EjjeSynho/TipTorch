    ax.set_yticklabels(pivot.index)
    ax.set_title('Wasserstein distance to on-sky / on-sky IQR, mean over wavelengths and TCs (lower is better)', fontsize=10)
    fig.colorbar(im, ax=ax, fraction=0.03)
    plt.tight_layout()
    fig.savefig(PLOTS_DIR / f'distance_scores{tag}.png', dpi=120, bbox_inches='tight')
    plt.close(fig)

    # paired scatter at 700 nm for the deterministic sources
    det = [s for s in ['tiptop', REFERENCE, 'impute', 'donor-mean', 'donor-params-nearest', 'direct-net'] if s in tables]
    fig, axes = plt.subplots(2, len(det), figsize=(3.6 * len(det), 7), squeeze=False)
    o = onsky[onsky.wave == 700].set_index('sample')
