def nearest_bins(wavelengths_nm, nominal):
    bins = [int(np.argmin(np.abs(np.asarray(wavelengths_nm) - w))) for w in nominal]
    return bins, [float(wavelengths_nm[b]) for b in bins]


def load_validation(etc_cal, dataset):
    """ Validation split as an ETC table (replayed real conditions) with sample ids, dates and the standardized real telemetry """
    val_idx = np.asarray(dataset.val_idx, int)
    tel_scaled = np.array([list(dataset.telemetry[i].values()) for i in val_idx], dtype=np.float32)
    tel_phys = pd.DataFrame(etc_cal.pre.inverse_transform(tel_scaled), columns=etc_cal.pre.features)
    etc = etc_table_from_telemetry(tel_phys)
    etc.insert(0, 'sample_id', np.asarray(dataset.sample_ids)[val_idx])
    etc.insert(1, 'dataset_idx', val_idx)
    dates = torch.load(DATASET_CACHE, weights_only=False, mmap=True)['acquisition_times']  # not kept by NFMDataset
    etc['date'] = pd.to_datetime(np.asarray(dates)[val_idx], utc=True, format='ISO8601').strftime('%Y-%m-%dT%H:%M:%S')
    return etc, tel_scaled


# metrics pool: the FWHM and the PSFAO fit run in worker processes (numpy / scipy / maoppy), the P3 metrics in the main process
def _measure_worker(args):
    psf, wave_nm, do_psfao = args
    out = {'fwhm': compute_fwhm(psf, pixel_scale_mas=PIXEL_SCALE_MAS), 'strehl': np.nan}
    if do_psfao:
        try:
            out['strehl'] = compute_strehl_psfao(psf, wave_nm)[0]
        except Exception as e:
            print(f'PSFAO fit failed: {type(e).__name__}: {e}')
    return out


def measure_PSFs(PSFs, waves_nm, pupil, processes=40, do_psfao=True, pool=None):
    """
    PSFs [N, N_wvl, H, W] (numpy; cropped to the 100 px field and normalized here) -> long table with one row per (sample, wavelength):
    `sample`, `wave` (nominal), `wave_nm`, `fwhm`, `strehl`, `strehl_tt`, `fwhm_tt`, `ensquared_tt`.
    """
    N, N_wvl = PSFs.shape[:2]
    cropped = [[normalize_psf(crop_center(np.asarray(PSFs[i, w], dtype=float))) for w in range(N_wvl)] for i in range(N)]
    jobs = [(cropped[i][w], waves_nm[w], do_psfao) for i in range(N) for w in range(N_wvl)]
    if pool is not None:
        res = pool.map(_measure_worker, jobs, chunksize=4)
    else:
        res = [_measure_worker(j) for j in jobs]
    rows = []
    for (i, w), r in zip(((i, w) for i in range(N) for w in range(N_wvl)), res):
        sr, fwhm_tt, ee = tiptop_metrics(cropped[i][w], waves_nm[w], pupil)
        rows.append({'sample': i, 'wave': NOMINAL_WAVES[w], 'wave_nm': waves_nm[w], 'fwhm': r['fwhm'], 'strehl': r['strehl'],
                     'strehl_tt': sr, 'fwhm_tt': fwhm_tt, 'ensquared_tt': ee})
    return pd.DataFrame(rows)


def attach_conditions(table, etc, source, draw=None):
    """ Adds the ETC conditions (seeing, tau0, airmass, ngs_mag, tc, sample_id, date) of `etc.iloc[sample]` and the source name """
    cols = ['sample_id', 'seeing', 'tau0', 'airmass', 'ngs_mag', 'tc', 'date']
    out = table.copy()
    for c in cols:
        out[c] = etc[c].to_numpy()[out['sample'].to_numpy()]
    out['source'] = source
    out['draw'] = 0 if draw is None else draw
    return out


def real_configs(dataset, idx, waves_nm):
    cfgs = []
    for i in idx:
        c = deepcopy(dataset.configs[i])
        c['sources_science']['Wavelength'] = [w * 1e-9 for w in waves_nm]
        c['telescope']['PathPupil'] = str(PUPIL_PATH)
        c['telescope']['PupilAngle'] = 0.0
        cfgs.append(c)
    return cfgs


@torch.no_grad()
def render_psfr(etc_cal, renderer, dataset, etc, tel_scaled, phase_bump=None, batch_size=16):
    """ PSF-R calibrator on the (possibly modified) standardized telemetry with the real configs -> PSFs [N, N_wvl, H, W] """
    cal = etc_cal.psfr_calibrator
    bump_value = etc_cal.phase_bump_median if phase_bump is None else phase_bump
    PSFs, params = [], []
    for start in range(0, len(etc), batch_size):
        ids = list(range(start, min(start + batch_size, len(etc))))
        x = cal.forward_prepared(torch.as_tensor(tel_scaled[ids], device=etc_cal.device))
        x['LO_coefs'] = torch.cat([torch.full((len(ids), 1), bump_value, device=etc_cal.device), x['LO_coefs'][:, 1:]], 1)
        model = renderer.make_model(real_configs(dataset, etc['dataset_idx'].to_numpy()[ids], renderer.wavelengths_nm))
        model.update_manager_params(x)
        PSFs.append(model().detach().cpu())
        params.append(pd.DataFrame(flatten_x_dict(x)))
        model.cleanup()
        del model
        release_gpu_memory()
    return torch.cat(PSFs, 0), pd.concat(params, ignore_index=True)


