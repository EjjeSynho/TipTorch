"""
Validation of ETC-regime PSF prediction for MUSE NFM (`calibrators/ETC_calibrator.py`, ExecPlan `agents/execplans/ETC_calibrator.md`).

The validation split of the calibrator dataset is replayed in the ETC regime: for every validation observation only the ETC
inputs (header seeing and tau0, airmass, NGS magnitude, IRLOS regime) are kept, PSFs are generated by every predictor at five
wavelengths (the dataset bins nearest to 500, 600, 700, 800, 900 nm) and measured with the ETC metrics of `ETC_psf_metrics`
(FWHM, PSFAO Strehl, peak-ratio Strehl, encircled energy within 50 mas). The same metrics are measured on the on-sky PSFs of the
same observations (dataset cubes, cropped to TIPTOP's 100 px field) and on vanilla TIPTOP run for the same conditions, so that
the parameter distributions can be compared per turbulence category (TC) and wavelength.

Stages (`--stage`, default all, each stage caches its table in `data/Enrico_ETC/ETC_calibrator/`):
  features   feature groups of the calibrator inputs; cross-validated predictability of the non-ETC features from the ETC inputs;
             gradient importance of the PSF-R calibrator per feature group; ablation of the feature groups (replaced by the trained
             imputer) in terms of the PSF metrics of the validation set
  onsky      metrics of the on-sky validation PSFs (+ Enrico's values where the observation is in `onsky_PSFs_params`)
  tiptop     vanilla TIPTOP (Enrico's tuned configuration) for the validation conditions, paired with the on-sky PSFs
  predict    PSFs of every predictor (see PREDICTORS; stochastic predictors are drawn `--draws` times) and the PSF-R calibrator
             on the real telemetry as the reference ceiling
  compare    distribution distances (Wasserstein-1, KS), paired errors, tables and figures in `data/Enrico_ETC/plots/ETC_calibrator/`

Requirements: the ETC bundle (`train_ETC_calibrator.py`), the PSF-R bundle it references, the dataset cache, a CUDA device, the
astro-tiptop checkouts (`development/tiptop_env.py`) for the metrics and the TIPTOP stage. Run from the repository root:

    python machine_learning/validate_ETC_calibrator.py [--stage onsky predict compare] [--draws 3] [--no-psfao] [--processes 40]
"""

